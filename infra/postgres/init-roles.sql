CREATE ROLE :"admin_user" LOGIN PASSWORD :'admin_password' NOSUPERUSER NOCREATEROLE NOCREATEDB;
CREATE ROLE :"app_user" LOGIN PASSWORD :'app_password' NOSUPERUSER NOCREATEROLE NOCREATEDB;

ALTER DATABASE :"dbname" OWNER TO :"admin_user";
ALTER SCHEMA public OWNER TO :"admin_user";

REVOKE ALL ON SCHEMA public FROM PUBLIC;
REVOKE CREATE ON DATABASE :"dbname" FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO :"app_user";

ALTER DEFAULT PRIVILEGES FOR ROLE :"admin_user" IN SCHEMA public
    GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO :"app_user";
ALTER DEFAULT PRIVILEGES FOR ROLE :"admin_user" IN SCHEMA public
    GRANT USAGE ON SEQUENCES TO :"app_user";
